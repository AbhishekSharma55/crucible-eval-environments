"""Human approval gate for exported evaluation environments.

`review` walks a reviewer through one candidate environment at a time and
appends their verdict to `environments/approvals.jsonl`. `promote` copies only
what a human explicitly accepted into `environments/approved/`.

No approval record is ever generated by a machine. The reviewer types the
verdict, and only `accept` promotes.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import shutil
from typing import Any

from scripts.export_environments import (
    APPROVALS, APPROVED_ROOT, CANDIDATE_ROOT, ENVIRONMENTS, GATES, GATE_TEXT, INDEX, sha256,
)
from scripts.phase3_common import json_dump


VERDICTS = {"a": "accept", "r": "reject", "u": "unsure"}
PROMOTABLE = "accept"
RULE = "=" * 78
TAIL = 2000

BANNER = """The five gates are NECESSARY, NOT SUFFICIENT.

They establish that this test fails at the broken commit, passes at the fixed
one, fails behaviourally, touches a line the fix changed, and edits nothing but
one new test file. They cannot establish that it captures the bug a user of this
library would recognise. A test can satisfy every gate and still assert
something incidental that happens to correlate with the fix.

That is what you are deciding. Read the issue, then read the test, and answer:
does this test fail for the reason the issue describes?"""


def utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def read_approvals(path: Path = APPROVALS) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            records.append(json.loads(line))
    return records


def append_approval(record: dict[str, Any], path: Path = APPROVALS) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record, sort_keys=True) + "\n")


def latest_verdicts(records: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """Last record wins, so a reviewer can correct an earlier verdict."""
    latest: dict[str, dict[str, Any]] = {}
    for record in records:
        latest[record["environment_id"]] = record
    return latest


def environment_dirs(root: Path = CANDIDATE_ROOT) -> list[Path]:
    if not root.is_dir():
        raise RuntimeError(f"no exported environments at {root}. Run: make export-environments")
    return sorted(path for path in root.iterdir() if (path / "metadata.json").is_file())


def tail(text: str, limit: int = TAIL) -> str:
    text = text or ""
    if len(text) <= limit:
        return text
    return f"[... {len(text) - limit} earlier characters omitted ...]\n" + text[-limit:]


def render(directory: Path, metadata: dict[str, Any], position: str) -> str:
    lines = [RULE, f"{position}  {metadata['environment_id']}  [{metadata['split']}]", RULE, ""]
    lines.append(f"repo        : {metadata['repo']}")
    lines.append(f"pull request: {metadata['pr_url']}  (merged {metadata['merged_at']})")
    lines.append(f"parent sha  : {metadata['parent_sha']}")
    lines.append(f"fix sha     : {metadata['fix_sha']}")
    lines.append(f"authored by : {metadata['authored_by']['model']} @ T={metadata['authored_by']['temperature']}")
    lines.append(f"test path   : {metadata['test_path']}")
    lines.append("")
    lines.append("-" * 78)
    lines.append("PROBLEM STATEMENT")
    lines.append("-" * 78)
    lines.append((directory / "problem_statement.md").read_text(encoding="utf-8").rstrip())
    lines.append("")
    lines.append("-" * 78)
    lines.append("AUTHORED TEST")
    lines.append("-" * 78)
    lines.append((directory / "test_patch.diff").read_text(encoding="utf-8").rstrip())
    lines.append("")
    lines.append("-" * 78)
    lines.append("GATE EVIDENCE")
    lines.append("-" * 78)
    for name in GATES:
        gate = metadata["gates"][name]
        lines.append(f"{name.upper()}  {gate['status']}  — {GATE_TEXT[name]}")
    coverage = metadata["coverage"]
    lines.append("")
    lines.append(
        f"G4 coverage fraction: {coverage['changed_line_fraction']}  "
        f"({coverage['covered_changed_line_count']}/{coverage['changed_line_count']} changed lines executed)"
    )
    for path, covered in sorted(coverage["covered_changed_lines"].items()):
        changed = coverage["changed_lines"].get(path, [])
        lines.append(f"  {path}: executed {covered} of changed {changed}")
    lines.append(f"transition kind     : {metadata['transition_kind']}")
    flags = metadata["gaming_flags"]
    lines.append(f"gate-gaming flags   : {', '.join(flags) if flags else 'none'}")
    if flags:
        lines.append("  Flags are review evidence only. They never rejected or selected anything.")
        lines.append("  Read the test above and decide for yourself.")
    lines.append("")
    lines.append("Parent run (bug present) — the test must fail here, for the right reason:")
    parent = metadata["gates"]["g1"]["evidence"]["runs"][0]
    lines.append(f"  exit code {parent['exit_code']}, outcomes {json.dumps(parent['outcomes'])}")
    lines.append(tail(parent.get("stdout_tail", "")))
    lines.append("")
    lines.append("Fix run (bug absent) — the same test must pass here:")
    fix = metadata["gates"]["g2"]["evidence"]["runs"][0]
    lines.append(f"  exit code {fix['exit_code']}, outcomes {json.dumps(fix['outcomes'])}")
    lines.append("")
    lines.append(f"Full evidence: {directory / 'metadata.json'}")
    lines.append(f"Re-check     : {directory / 'verify.sh'}")
    lines.append("")
    lines.append(BANNER)
    lines.append("")
    return "\n".join(lines)


def review(reviewer: str, *, root: Path = CANDIDATE_ROOT, approvals: Path = APPROVALS, redo: bool = False) -> int:
    directories = environment_dirs(root)
    decided = {
        record["environment_id"] for record in read_approvals(approvals)
        if record.get("reviewer") == reviewer
    }
    pending = [path for path in directories if redo or path.name not in decided]
    print(f"{len(directories)} candidate environments, {len(decided)} already reviewed by {reviewer!r},"
          f" {len(pending)} to go.")
    if not pending:
        print("Nothing left to review. Run: make promote-environments")
        return 0
    for offset, directory in enumerate(pending):
        metadata = json.loads((directory / "metadata.json").read_text(encoding="utf-8"))
        position = f"[{len(decided) + offset + 1}/{len(directories)}]"
        print("\n" + render(directory, metadata, position))
        while True:
            choice = input("Verdict [a=accept, r=reject, u=unsure, q=save/quit]: ").strip().lower()
            if choice == "q":
                print(f"stopped. {len(decided) + offset} of {len(directories)} reviewed by {reviewer!r}.")
                print("Re-run the same command to resume where you left off.")
                return 0
            if choice in VERDICTS:
                break
        note = input("Note (why — free text, optional): ").strip()
        append_approval({
            "schema_version": 1,
            "environment_id": metadata["environment_id"],
            "case_id": metadata["case_id"],
            "split": metadata["split"],
            "verdict": VERDICTS[choice],
            "note": note,
            "reviewer": reviewer,
            "reviewed_at": utc_now(),
            "test_patch_sha256": sha256((directory / "test_patch.diff").read_text(encoding="utf-8")),
        }, approvals)
    print(f"\ncomplete: {len(directories)} environments reviewed by {reviewer!r}.")
    print("Run: make promote-environments")
    return 0


def promotion_decision(directory: Path, record: dict[str, Any] | None) -> tuple[bool, str]:
    """Decide whether one environment may be promoted. Refusals are explicit."""
    if record is None:
        return False, "refused: no human review record"
    if record.get("verdict") != PROMOTABLE:
        return False, f"refused: latest human verdict is {record.get('verdict')!r}, not 'accept'"
    if not record.get("reviewer"):
        return False, "refused: approval record names no reviewer"
    current = sha256((directory / "test_patch.diff").read_text(encoding="utf-8"))
    if record.get("test_patch_sha256") != current:
        return False, "refused: test_patch.diff changed since it was accepted; re-review it"
    return True, f"accepted by {record['reviewer']} at {record['reviewed_at']}"


def promote(*, root: Path = CANDIDATE_ROOT, approvals: Path = APPROVALS, destination: Path = APPROVED_ROOT) -> int:
    directories = environment_dirs(root)
    latest = latest_verdicts(read_approvals(approvals))
    promoted: list[dict[str, Any]] = []
    refused = 0
    for directory in directories:
        allowed, explanation = promotion_decision(directory, latest.get(directory.name))
        if not allowed:
            refused += 1
            print(f"  [skip] {directory.name}: {explanation}")
            continue
        record = latest[directory.name]
        target = destination / directory.name
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(directory, target)
        json_dump(target / "approval.json", record)
        print(f"  [ok  ] {directory.name}: {explanation}")
        promoted.append({
            "environment_id": directory.name,
            "case_id": record["case_id"],
            "split": record["split"],
            "reviewer": record["reviewer"],
            "reviewed_at": record["reviewed_at"],
            "note": record["note"],
        })
    print(f"\npromoted {len(promoted)} of {len(directories)}; refused {refused}.")
    if not promoted:
        print("Refusing to promote anything: no environment carries an explicit human 'accept'.")
        print("Run: make review-environments REVIEWER='your name'")
        return 2
    destination.mkdir(parents=True, exist_ok=True)
    json_dump(destination / "index.json", {
        "schema_version": 1,
        "count": len(promoted),
        "note": "Every entry here carries an explicit human accept in environments/approvals.jsonl.",
        "environments": promoted,
    })
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command")
    review_parser = sub.add_parser("review", help="walk a human through the candidate environments")
    review_parser.add_argument("--reviewer", required=True, help="real human's name or stable identity")
    review_parser.add_argument("--candidates", type=Path, default=CANDIDATE_ROOT)
    review_parser.add_argument("--approvals", type=Path, default=APPROVALS)
    review_parser.add_argument("--redo", action="store_true", help="re-review environments already decided")
    promote_parser = sub.add_parser("promote", help="copy accepted environments into approved/")
    promote_parser.add_argument("--candidates", type=Path, default=CANDIDATE_ROOT)
    promote_parser.add_argument("--approvals", type=Path, default=APPROVALS)
    promote_parser.add_argument("--destination", type=Path, default=APPROVED_ROOT)
    args = parser.parse_args(argv)
    if args.command == "promote":
        return promote(root=args.candidates, approvals=args.approvals, destination=args.destination)
    if args.command == "review":
        return review(args.reviewer, root=args.candidates, approvals=args.approvals, redo=args.redo)
    parser.print_help()
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
